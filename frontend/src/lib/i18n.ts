export type TranslationKey = keyof typeof translations.en;

// Client-side language detection
export function detectClientLanguage(): LanguageCode {
  // First check cookie for user preference
  const cookieLang = getCookie(LANGUAGE_COOKIE_NAME) as LanguageCode;
  
  if (cookieLang && cookieLang in supportedLanguages) {
    return cookieLang;
  }
  
  // Then check browser language
  if (typeof navigator !== 'undefined') {
    const browserLanguage = navigator.language.toLowerCase().split('-')[0] as LanguageCode;
    if (browserLanguage in supportedLanguages) {
      return browserLanguage;
    }
  }
  
  return defaultLanguage;
}

// Helper function to get cookie value (client-side)
function getCookie(name: string): string | null {
  if (typeof document === 'undefined') return null;
  
  const value = `; ${document.cookie}`;
  const parts = value.split(`; ${name}=`);
  if (parts.length === 2) {
    return parts.pop()?.split(';').shift() || null;
  }
  return null;
}

// Helper function to set cookie (client-side)
export function setCookie(name: string, value: string, days: number = 365): void {
  if (typeof document === 'undefined') return;
  
  const expires = new Date();
  expires.setTime(expires.getTime() + days * 24 * 60 * 60 * 1000);
  document.cookie = `${name}=${value};expires=${expires.toUTCString()};path=/`;
}

// Translation function
export function t(key: TranslationKey, lang: LanguageCode = defaultLanguage): string {
  const langTranslations = translations[lang] || translations[defaultLanguage];
  return langTranslations[key] || translations[defaultLanguage][key] || key;
}

// Set language preference (client-side)
export function setLanguage(lang: LanguageCode): void {
  if (lang in supportedLanguages) {
    setCookie(LANGUAGE_COOKIE_NAME, lang);
  }
}

// Get current language (client-side)
export function getCurrentLanguage(): LanguageCode {
  return detectClientLanguage();
}

// Language context interface for React components
export interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: TranslationKey) => string;
}
